/* Renders the first page of every form into a picture of itself.
 *
 *   node tools/build-previews.mjs [--force]
 *
 * The library used to show one drawn illustration on all ninety cards, which
 * told you nothing: a tax return and a lease looked identical, and the only way
 * to find out which form you were about to open was to open it. A thumbnail of
 * the real page is worth more than any illustration, because it is the thing
 * itself — you recognise a W-9 at 240 pixels wide without reading a word of it.
 *
 * Two sizes come out of one render. The card is small and lazy-loaded, so a
 * page of ninety costs a couple of hundred kilobytes; the detail preview is
 * large enough to read the headings on the form page. Both are WebP, which at
 * this size is roughly a third of what the equivalent PNG would be.
 *
 * The official forms are files on disk. The templates are not files at all —
 * they are built from a description at the moment you ask for one — so this
 * runs the same builder the browser runs and rasterises what it produces. That
 * matters: the preview is then generated by the code that generates the form,
 * and the two cannot drift apart.
 */
import {readFileSync, writeFileSync, existsSync, mkdirSync, statSync, readdirSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createCanvas} from '@napi-rs/canvas';
import {PDFDocument} from 'pdf-lib';
import {FORMS} from './shared.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILES = join(ROOT, 'forms', 'files');
const OUT = join(ROOT, 'forms', 'previews');
const force = process.argv.includes('--force');

/* The card is displayed at about 230 CSS pixels, the detail preview at about
   440, and both are rendered well above that so they hold up on a dense
   display — the same reason the page rail renders above 1:1.
   Quality barely moves the file size on a page of black text on white: 480px
   at q52 and at q74 are within 15% of each other, because what costs the bytes
   is the sharp edges, not the fidelity. The dimension is the lever, so these
   are sized honestly and left at a quality that does not smudge the type. */
const SIZES = [
  {suffix: '', width: 400, quality: 70},
  {suffix: '@lg', width: 760, quality: 76},
];

mkdirSync(OUT, {recursive: true});

/* pdf.js narrates missing standard fonts and objects it repairs. Neither says
   anything a person building the site can act on. */
function quiet() {
  const {log, warn, error} = console;
  console.log = console.warn = console.error = () => {};
  return () => { console.log = log; console.warn = warn; console.error = error; };
}

const {getDocument} = await import('pdfjs-dist/legacy/build/pdf.mjs');

async function firstPage(bytes) {
  /* A copy: pdf.js hands the buffer to its worker, which detaches it. */
  const task = getDocument({data: bytes.slice(), useSystemFonts: false, isEvalSupported: false});
  const doc = await task.promise;
  const page = await doc.getPage(1);
  return {page, done: () => task.destroy()};
}

async function render(bytes, width) {
  const {page, done} = await firstPage(bytes);
  try {
    const base = page.getViewport({scale: 1});
    const viewport = page.getViewport({scale: width / base.width});
    const canvas = createCanvas(Math.ceil(viewport.width), Math.ceil(viewport.height));
    const ctx = canvas.getContext('2d');
    /* Paper is white. Without this the transparent areas of a form come out
       black once WebP drops the alpha channel. */
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    await page.render({canvasContext: ctx, viewport}).promise;
    return canvas;
  } finally {
    await done();
  }
}

/* The templates have no file to read, so the builder is run here exactly as the
   browser runs it. Node strips the types; nothing is compiled and there is no
   second copy of the layout code to keep in step. */
async function templateBytes(slug, cache) {
  if (!cache.specs) {
    cache.specs = (await import('../app/core/formSpecs.ts')).FORM_SPECS;
    cache.build = (await import('../app/core/formDocs.ts')).buildForm;
  }
  const spec = cache.specs[slug];
  if (!spec) return null;
  const doc = await PDFDocument.create();
  await cache.build(doc, spec);
  return doc.save();
}

const cache = {};
const made = [];
const missing = [];
const restore = quiet();

for (const form of FORMS) {
  const targets = SIZES.map(s => join(OUT, `${form.slug}${s.suffix}.webp`));
  if (!force && targets.every(t => existsSync(t) && statSync(t).size > 0)) continue;

  let bytes = null;
  if (form.hosted) {
    const file = join(FILES, `${form.slug}.pdf`);
    if (existsSync(file)) bytes = new Uint8Array(readFileSync(file));
  } else {
    try { bytes = await templateBytes(form.slug, cache); } catch { bytes = null; }
  }
  if (!bytes) { missing.push(form.slug); continue; }

  try {
    for (const [i, size] of SIZES.entries()) {
      const canvas = await render(bytes, size.width);
      writeFileSync(targets[i], await canvas.encode('webp', size.quality));
    }
    made.push(form.slug);
  } catch (err) {
    missing.push(`${form.slug} (${String(err.message).slice(0, 40)})`);
  }
}

restore();

const total = readdirSync(OUT).filter(f => f.endsWith('.webp'));
const kb = total.reduce((n, f) => n + statSync(join(OUT, f)).size, 0) / 1024;
console.log(`  previews — ${made.length} rendered, ${total.length} files, ${(kb / 1024).toFixed(1)} MB`);
if (missing.length) console.log(`  no preview for: ${missing.join(', ')}`);
