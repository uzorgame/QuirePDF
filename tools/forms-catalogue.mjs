/* Which official forms we host, and where each one comes from.
 *
 * Works of the United States federal government are not under copyright
 * (17 U.S.C. §105), so these can be redistributed. That is the reason the list
 * is federal-only: state, county and university forms carry no such blanket
 * rule, and a university's internal receipt form is not something to mirror on
 * a stranger's site.
 *
 * Every entry is verified at build time — downloaded, parsed, and re-saved. A
 * form that cannot make that round trip is not shipped, because it would break
 * at export in the user's hands instead of here.
 *
 * `source` is the human page at the agency, not the file. It is shown on every
 * form page so anyone can check they have the current revision, which matters:
 * a superseded tax form filed in good faith is still a rejected filing. */

const irs = (file) => `https://www.irs.gov/pub/irs-pdf/${file}.pdf`;
const uscis = (file) => `https://www.uscis.gov/sites/default/files/document/forms/${file}.pdf`;
const ssa = (file) => `https://www.ssa.gov/forms/${file}.pdf`;
/* The State Department has two naming schemes side by side and no rule about
   which form gets which: ds64.pdf and ds3053.pdf resolve, ds11.pdf and
   ds82.pdf do not — those want a `_pdf` suffix. Both are spelled out per form
   rather than guessed at, because the wrong one is a plain 404. */
const state = (file) => `https://eforms.state.gov/Forms/${file}.pdf`;
/* The VA serves its fillable forms from vba.va.gov, not from the va.gov path
   the "find a form" pages link to — that one 404s for every form. */
const va = (file) => `https://www.vba.va.gov/pubs/forms/${file}.pdf`;

const IRS_PAGE = (n) => `https://www.irs.gov/forms-pubs/about-form-${n}`;

